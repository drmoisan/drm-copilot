"""Structural contract tests for the generated legacy-discovery skills.

Issue #980 replaced the seven duplicated ``discovery-*`` workflow procedures
with nine canonical workflow skills and seven thin dispatch aliases. The
``.github/skills`` sources are canonical; the Claude (``.claude/skills``) and
shared Codex (``.agents/skills``) copies are generated by a deterministic
role-link rewrite and mirrored byte-identically into the extension bundles.
These tests pin frontmatter, routing, alias thinness, neutrality, name
non-collision, generation parity, and bundle mirroring for all sixteen skills.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[3]
BUNDLED_CLAUDE_ROOT = (
    REPO_ROOT / "extensions" / "drm-copilot" / "resources" / "claude-customizations"
)
BUNDLED_CODEX_ROOT = (
    REPO_ROOT
    / "extensions"
    / "drm-copilot"
    / "resources"
    / "codex-and-agents-customizations"
)

# Nine canonical workflows and the fixed logical role each one routes to.
WORKFLOW_ROLES: dict[str, str] = {
    "inventory-legacy-system": "legacy-parity-analyst",
    "extract-feature-contract": "legacy-parity-analyst",
    "characterize-runtime-behavior": "runtime-characterization-analyst",
    "reconcile-parity-matrix": "requirements-reconciler",
    "review-discovery-coverage": "migration-coverage-reviewer",
    "adjudicate-unspecified-behavior": "requirements-reconciler",
    "generate-acceptance-scenarios": "requirements-reconciler",
    "initialize-discovery-workspace": "migration-coverage-reviewer",
    "validate-discovery-artifacts": "migration-coverage-reviewer",
}
# Seven compatibility aliases and the canonical workflows they dispatch to.
ALIAS_TARGETS: dict[str, tuple[str, ...]] = {
    "discovery-workflow": tuple(WORKFLOW_ROLES),
    "discovery-repo-inventory": ("inventory-legacy-system",),
    "discovery-coverage-ledger": (
        "inventory-legacy-system",
        "extract-feature-contract",
        "review-discovery-coverage",
    ),
    "discovery-runtime-characterization": ("characterize-runtime-behavior",),
    "discovery-parity-matrix": ("reconcile-parity-matrix",),
    "discovery-behavior-reconciliation": ("adjudicate-unspecified-behavior",),
    "discovery-validate-artifacts": ("validate-discovery-artifacts",),
}
WORKFLOW_NAMES: tuple[str, ...] = tuple(WORKFLOW_ROLES)
ALIAS_NAMES: tuple[str, ...] = tuple(ALIAS_TARGETS)
SKILL_NAMES: tuple[str, ...] = WORKFLOW_NAMES + ALIAS_NAMES
FOUR_ROLES: frozenset[str] = frozenset(WORKFLOW_ROLES.values())

# Sections every workflow must carry and no alias may duplicate.
WORKFLOW_ONLY_SECTIONS: tuple[str, ...] = (
    "## Routing",
    "## Exact output boundary",
    "## Prerequisites",
    "## Step-by-Step Workflows",
)
# Superseded fragments of the pre-#980 alias bodies that must not return.
RETIRED_FRAGMENTS: tuple[str, ...] = (
    "Fan-in reconciliation assumption",
    "dev.discovery.",
    "schemas/discovery/v1/",
    "## Worker Routing",
    "## Referenced Contracts",
    "allowed-tools:",
)
# Source-ecosystem references that a generated copy must never carry.
SOURCE_ECOSYSTEM_FRAGMENTS: tuple[str, ...] = (
    ".github/",
    ".agent.md",
    "drmcopilotextension",
)
BANNED_SUBSTRINGS: frozenset[str] = frozenset(
    {
        "taskmaster",
        "tmw",
        "outlook",
        "vsto",
        "email",
        "task-management",
        "task management",
    }
)
CODE_MODERNIZATION_NAMES: frozenset[str] = frozenset(
    {
        "modernize-assess",
        "modernize-brief",
        "modernize-extract-rules",
        "modernize-harden",
        "modernize-map",
        "modernize-preflight",
        "modernize-reimagine",
        "modernize-status",
        "modernize-transform",
        "modernize-uplift",
        "legacy-analyst",
        "business-rules-extractor",
        "architecture-critic",
        "scaffolder",
        "security-auditor",
        "test-engineer",
        "version-delta-analyst",
    }
)
ROLE_LINK = re.compile(r"\]\(\.\./\.\./agents/([a-z-]+)\.agent\.md\)")


def canonical_path(skill_name: str) -> Path:
    """Return the repo-relative path of a skill's canonical GitHub source.

    Args:
        skill_name (str): The skill folder name.

    Returns:
        Path: The ``.github/skills/<name>/SKILL.md`` relative path.
    """

    return Path(".github") / "skills" / skill_name / "SKILL.md"


def claude_path(skill_name: str) -> Path:
    """Return the repo-relative path of a skill's generated Claude copy.

    Args:
        skill_name (str): The skill folder name.

    Returns:
        Path: The ``.claude/skills/<name>/SKILL.md`` relative path.
    """

    return Path(".claude") / "skills" / skill_name / "SKILL.md"


def codex_path(skill_name: str) -> Path:
    """Return the repo-relative path of a skill's generated shared Codex copy.

    Args:
        skill_name (str): The skill folder name.

    Returns:
        Path: The ``.agents/skills/<name>/SKILL.md`` relative path.
    """

    return Path(".agents") / "skills" / skill_name / "SKILL.md"


def read_text(root: Path, relative_path: Path) -> str:
    """Return the UTF-8 text of a file addressed relative to a root.

    Args:
        root (Path): Repository root or bundle root.
        relative_path (Path): Root-relative file path.

    Returns:
        str: The decoded file content.

    Raises:
        FileNotFoundError: If the file does not exist.
    """

    return (root / relative_path).read_text(encoding="utf-8")


def _description_line(skill_text: str) -> str | None:
    """Return the first ``description:`` frontmatter line, or None.

    Args:
        skill_text (str): Full SKILL.md text.

    Returns:
        str | None: The stripped line when present.
    """

    # The frontmatter precedes the body, so the first match is the metadata.
    for line in skill_text.splitlines():
        if line.startswith("description:"):
            return line.strip()
    return None


@pytest.mark.parametrize("skill_name", SKILL_NAMES)
def test_generated_skill_copies_exist(skill_name: str) -> None:
    """Each skill exists canonically, in Claude, and as a shared Codex skill."""

    for relative_path in (
        canonical_path(skill_name),
        claude_path(skill_name),
        codex_path(skill_name),
    ):
        assert (REPO_ROOT / relative_path).is_file(), f"missing: {relative_path}"


@pytest.mark.parametrize("skill_name", SKILL_NAMES)
def test_skill_frontmatter_name_and_description(skill_name: str) -> None:
    """Frontmatter name matches the folder and the description is single-quoted."""

    skill_text = read_text(REPO_ROOT, claude_path(skill_name))

    assert f"name: {skill_name}\n" in skill_text, f"name mismatch: {skill_name}"
    description_line = _description_line(skill_text)
    assert description_line is not None, f"missing description: {skill_name}"
    assert description_line.startswith("description: '"), skill_name
    inner = description_line[len("description: '") :]
    assert inner.endswith("'") and inner[:-1].strip(), skill_name


@pytest.mark.parametrize(("skill_name", "role"), sorted(WORKFLOW_ROLES.items()))
def test_workflow_routes_to_one_fixed_role_with_zero_writes(
    skill_name: str, role: str
) -> None:
    """Each workflow names one logical role and a zero production-write count."""

    skill_text = read_text(REPO_ROOT, claude_path(skill_name))

    assert f"Logical role: `{role}`." in skill_text, skill_name
    assert "The production-write count is zero." in skill_text, skill_name
    # No other role may be named as the routed logical role of this workflow.
    other_roles = {f"Logical role: `{name}`." for name in FOUR_ROLES - {role}}
    assert not any(other in skill_text for other in other_roles), skill_name
    for section in WORKFLOW_ONLY_SECTIONS:
        assert section in skill_text, f"{skill_name} missing {section}"
    assert "`finalize_discovery_agent`" in skill_text, skill_name
    assert "`mode=agent-output`" in skill_text, skill_name
    assert "`required-output-manifest`" in skill_text, skill_name


@pytest.mark.parametrize(("skill_name", "role"), sorted(WORKFLOW_ROLES.items()))
def test_workflow_links_its_native_role_contract(skill_name: str, role: str) -> None:
    """Claude and Codex copies link the role through their own native path."""

    claude_text = read_text(REPO_ROOT, claude_path(skill_name))
    codex_text = read_text(REPO_ROOT, codex_path(skill_name))

    assert f"](../../../.claude/agents/{role}.md)" in claude_text, skill_name
    assert f"](../../../.codex/agents/{role}.toml)" in codex_text, skill_name
    assert ".claude/" not in codex_text, f"Claude path in Codex copy: {skill_name}"
    assert ".codex/" not in claude_text, f"Codex path in Claude copy: {skill_name}"


@pytest.mark.parametrize(("skill_name", "targets"), sorted(ALIAS_TARGETS.items()))
def test_alias_dispatches_only_to_its_canonical_targets(
    skill_name: str, targets: tuple[str, ...]
) -> None:
    """Each alias dispatches to exactly its targets and carries no workflow body."""

    skill_text = read_text(REPO_ROOT, claude_path(skill_name))

    assert "## Dispatch" in skill_text, skill_name
    assert "no independent output or write authority" in skill_text, skill_name
    linked = set(re.findall(r"\]\(\.\./([a-z-]+)/SKILL\.md\)", skill_text))
    assert linked == set(targets), f"{skill_name} links {sorted(linked)}"
    # A thin alias repeats none of the semantic workflow sections.
    for section in WORKFLOW_ONLY_SECTIONS:
        assert section not in skill_text, f"{skill_name} duplicates {section}"


@pytest.mark.parametrize("skill_name", SKILL_NAMES)
def test_retired_and_source_ecosystem_fragments_absent(skill_name: str) -> None:
    """Generated copies carry no superseded v1 procedure or source-only reference."""

    claude_text = read_text(REPO_ROOT, claude_path(skill_name))
    codex_text = read_text(REPO_ROOT, codex_path(skill_name))

    for fragment in RETIRED_FRAGMENTS + SOURCE_ECOSYSTEM_FRAGMENTS:
        assert fragment not in claude_text, f"{skill_name} retains {fragment}"
        assert fragment not in codex_text, f"{skill_name} retains {fragment}"


@pytest.mark.parametrize("skill_name", SKILL_NAMES)
def test_banned_substrings_absent(skill_name: str) -> None:
    """No skill text contains a product-specific banned substring."""

    skill_text_lower = read_text(REPO_ROOT, claude_path(skill_name)).lower()

    for banned in sorted(BANNED_SUBSTRINGS):
        assert banned not in skill_text_lower, f"{skill_name} contains {banned}"


@pytest.mark.parametrize("skill_name", SKILL_NAMES)
def test_skill_name_does_not_collide_with_code_modernization(skill_name: str) -> None:
    """No skill name collides with the code-modernization plugin name set."""

    assert skill_name not in CODE_MODERNIZATION_NAMES, skill_name


@pytest.mark.parametrize("skill_name", SKILL_NAMES)
def test_generated_copies_are_the_deterministic_role_link_rewrite(
    skill_name: str,
) -> None:
    """Claude and Codex copies equal the canonical source under the fixed rewrite."""

    canonical_text = read_text(REPO_ROOT, canonical_path(skill_name))
    expected_claude = ROLE_LINK.sub(r"](../../../.claude/agents/\1.md)", canonical_text)
    expected_codex = ROLE_LINK.sub(r"](../../../.codex/agents/\1.toml)", canonical_text)

    assert read_text(REPO_ROOT, claude_path(skill_name)) == expected_claude, skill_name
    assert read_text(REPO_ROOT, codex_path(skill_name)) == expected_codex, skill_name


@pytest.mark.parametrize("skill_name", SKILL_NAMES)
def test_skill_is_mirrored_into_both_bundled_payloads(skill_name: str) -> None:
    """Each generated copy is byte-identical in its extension bundle."""

    claude_relative = claude_path(skill_name)
    codex_relative = codex_path(skill_name)

    assert read_text(REPO_ROOT, claude_relative) == read_text(
        BUNDLED_CLAUDE_ROOT, claude_relative
    ), f"Claude bundle drift: {claude_relative}"
    assert read_text(REPO_ROOT, codex_relative) == read_text(
        BUNDLED_CODEX_ROOT, codex_relative
    ), f"Codex bundle drift: {codex_relative}"


def test_sixteen_skills_route_to_exactly_four_roles() -> None:
    """The inventory is nine workflows, seven aliases, and four logical roles."""

    assert len(WORKFLOW_NAMES) == 9
    assert len(ALIAS_NAMES) == 7
    assert len(SKILL_NAMES) == len(set(SKILL_NAMES)) == 16
    assert FOUR_ROLES == {
        "legacy-parity-analyst",
        "runtime-characterization-analyst",
        "requirements-reconciler",
        "migration-coverage-reviewer",
    }
    # Every alias target is one of the nine canonical workflows.
    for targets in ALIAS_TARGETS.values():
        assert set(targets) <= set(WORKFLOW_NAMES)
