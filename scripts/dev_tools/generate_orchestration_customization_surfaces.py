SurfaceFamily = Literal["reviewer", "orchestrator", "researcher"]
_FamilyMap = dict[str, SurfaceFamily]
_HANDOFF = "Delegate permitted remediation planning through the canonical contract."
_AUDIT = "Review a feature branch and emit deterministic audit and remediation results."
_ORCHESTRATION = "Coordinate deterministic repository orchestration and remediation."
_ORCH_RULE = "Enforce canonical orchestration and remediation state transitions."


@dataclass(frozen=True)
class Surface:
    """Describe one generated customization surface."""

    path: Path
    family: SurfaceFamily
    kind: str
    name: str
    description: str
    prompt_agent: str | None = None


def _declared_surface(row: str) -> Surface:
    """Parse one validated compact inventory row without changing its order."""
    fields = row.split("|")
    family_code, path, kind, name, prompt_agent = fields
    if family_code not in _FAMILY_CODES:
        raise ValueError(f"Unknown surface family code: {family_code!r}")
    family = _FAMILY_CODES[family_code]
    if family == "reviewer":
        description = (
            _HANDOFF
            if name == "remediation-handoff-atomic-planner"
            else {
                "prompt": "Run the canonical feature-review workflow.",
                "skill": "Execute the canonical feature-review workflow.",
            }.get(kind, _AUDIT)
        )
    elif family == "orchestrator":
        if kind == "prompt":
            scope = {
                "orchestrate-work": "repository",
                "orchestrate-python-work": "Python",
                "orchestrate-powershell-work": "PowerShell",
                "orchestrate-csharp-work": "C#",
            }[name]
            description = f"Run deterministic {scope} orchestration."
        else:
            description = {
                "github-agent": _ORCHESTRATION,
                "claude-agent": _ORCHESTRATION,
                "skill": (
                    "Route work through deterministic orchestration and remediation."
                ),
                "rule": _ORCH_RULE,
            }[kind]
    elif kind in {"prompt", "skill"}:
        description = "Research an issue within the orchestrator-supplied tracked root."
    else:
        description = (
            "Research within the exact tracked root supplied by the orchestrator."
        )
    return Surface(Path(path), family, kind, name, description, prompt_agent)


